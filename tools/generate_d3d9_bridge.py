"""Generate explicit guest32 COM calls from the pinned DXVK native D3D9 ABI.

No target-game addresses, handwritten vtable guesses, or host pointer casts.
The included headers retain their upstream licenses; this generator emits
mechanical API calls rather than copying another game's adapter.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
INTERFACES=["IDirect3D9","IDirect3DDevice9","IDirect3DTexture9","IDirect3DCubeTexture9",
    "IDirect3DSurface9","IDirect3DVertexBuffer9","IDirect3DIndexBuffer9",
    "IDirect3DVertexShader9","IDirect3DPixelShader9","IDirect3DVertexDeclaration9",
    "IDirect3DStateBlock9","IDirect3DQuery9","IDirect3DSwapChain9","IDirect3DVolumeTexture9","IDirect3DVolume9"]
KINDS={name:i+1 for i,name in enumerate(INTERFACES)}
COUNTS=[17,119,22,22,17,14,14,5,5,5,6,8,10,22,11]
# Pointer-sized structures, returned pointers, native callback functions, locks,
# and opaque OS handles need explicit code rather than a native struct cast.
SPECIAL={
 "IDirect3D9":{"RegisterSoftwareDevice","GetAdapterIdentifier","GetAdapterMonitor","CreateDevice"},
 "IDirect3DDevice9":{"GetCreationParameters","CreateAdditionalSwapChain","Reset","Present","GetNPatchMode"},
 "IDirect3DTexture9":{"LockRect","UnlockRect"},
 "IDirect3DCubeTexture9":{"LockRect","UnlockRect"},
 "IDirect3DSurface9":{"GetContainer","LockRect","UnlockRect","GetDC","ReleaseDC"},
 "IDirect3DVertexBuffer9":{"Lock","Unlock"},"IDirect3DIndexBuffer9":{"Lock","Unlock"},
 "IDirect3DSwapChain9":{"Present","GetPresentParameters"},
 "IDirect3DVolumeTexture9":{"LockBox","UnlockBox"},
 "IDirect3DVolume9":{"GetContainer","LockBox","UnlockBox"},
}

def methods(header: str,name: str):
    match=re.search(r"DECLARE_INTERFACE_\("+name+r",\s*\w+\)\s*\{(.*?)\n\};",header,re.S)
    if not match: raise ValueError(f"Interface missing: {name}")
    found=re.findall(r"STDMETHOD(?:_\(\s*([^,]+),\s*(\w+)\)|\((\w+)\))\s*\((.*?)\)\s*PURE",match[1],re.S)
    result=[]
    for output,typed,ordinary,raw in found:
        raw=re.sub(r"\s+"," ",raw).strip()
        raw=raw[5:].strip() if raw.startswith("THIS_") else "" if raw=="THIS" else raw
        params=[]
        for param in raw.split(",") if raw else []:
            param=param.strip().removeprefix("struct ")
            # Some methods have an unnamed enum/pointer parameter.
            if not re.fullmatch(r"(?:const )?[A-Za-z_]\w*\s*\**",param):
                param=re.sub(r"\b[A-Za-z_]\w*$","",param).strip()
            param=re.sub(r"\s*\*\s*","*",param)
            params.append(param)
        result.append((typed or ordinary,output.strip() or "HRESULT",params))
    return result

def generate(header: str):
    calls=["// Generated by tools/generate_d3d9_bridge.py from pinned DXVK native d3d9.h.\n"]
    wrappers=[calls[0]];metadata=[]
    for kind,name in enumerate(INTERFACES,1):
        entries=methods(header,name)
        if len(entries)!=COUNTS[kind-1]:raise ValueError(f"Unexpected {name} method count {len(entries)}")
        calls.append(f"if(kind=={kind}){{auto resource=static_cast<{name}*>(object);switch(method){{\n")
        for slot,(method,result,params) in enumerate(entries):
            count=1+len(params); symbol=f"tf_d3d9_{kind}_{slot}"
            wrappers.append(f"static void {symbol}(void){{tf_d3d9_hle_method({kind},{slot},{count});}}\n")
            metadata.append({"kind":kind,"interface":name,"slot":slot,"method":method,"argc":count})
            if slot<3 or method in SPECIAL.get(name,set()):continue
            before=[];after=[];args=[]
            for index,type_name in enumerate(params,1):
                word=f"args[{index}]"
                if type_name.endswith("**") and type_name[:-2] in KINDS:
                    interface=type_name[:-2];variable=f"out{index}"
                    before.append(f"{interface} *{variable}=nullptr;")
                    args.append(f"{word}?&{variable}:nullptr")
                    after.append(f"if({word})write({word},SUCCEEDED(status)?wrap({variable},{KINDS[interface]}):0);")
                elif type_name=="IDirect3DBaseTexture9**":
                    before.append(f"IDirect3DBaseTexture9 *out{index}=nullptr;")
                    args.append(f"{word}?&out{index}:nullptr")
                    after.append(f"if({word})write({word},SUCCEEDED(status)?wrap_texture(out{index}):0);")
                elif type_name.startswith("IDirect3D") and type_name.endswith("*"):
                    args.append(f"native_object<{type_name[:-1]}>({word})")
                elif type_name=="HANDLE*":
                    before.append(f'if({word})unsupported("shared resource handles");');args.append("nullptr")
                elif type_name in ("REFIID","REFGUID"):
                    args.append(f"*guest<GUID>({word})")
                elif type_name=="HWND": args.append("native_window()")
                elif "*" in type_name:
                    base=type_name.replace("const ","").rstrip("*")
                    if base=="void":args.append(f"pointer({word})")
                    elif base in {"D3DPRESENT_PARAMETERS","D3DLOCKED_RECT","D3DLOCKED_BOX","D3DDEVICE_CREATION_PARAMETERS","HDC","HANDLE"}:
                        raise ValueError(f"Unmarshalled {name}::{method} {type_name}")
                    else:args.append(f"guest<{base}>({word})")
                elif type_name=="float": args.append(f"float_value({word})")
                else:args.append(f"static_cast<{type_name}>({word})")
            if method=="SetPrivateData":before.insert(0,'if(args[4]&D3DSPD_IUNKNOWN)unsupported("private IUnknown data");')
            invocation=f"resource->{method}({','.join(args)})"
            calls.append(f"case {slot}:{{*argument_count={count};"+"".join(before))
            if after:calls.append(f"HRESULT status={invocation};"+"".join(after)+"return status;}")
            elif result=="void":calls.append(invocation+";return 0;}")
            elif result=="float":calls.append(f"return float_bits({invocation});}}")
            elif result in {"HRESULT","ULONG","UINT","DWORD","WINBOOL","D3DRESOURCETYPE","D3DTEXTUREFILTERTYPE","D3DQUERYTYPE"}:calls.append(f"return {invocation};}}")
            else:raise ValueError(f"Unexpected return type {result}")
            calls.append("\n")
        calls.append("}}\n")
    wrappers.append("static const win32hle_shim tf_d3d9_method_shims[]={\n")
    for item in metadata:
        k,s=item["kind"],item["slot"]
        wrappers.append(f'{{"TF.D3D9.{k}.{s}",tf_d3d9_{k}_{s}}},\n')
    wrappers.append("{nullptr,nullptr}};\n")
    return "".join(calls),"".join(wrappers),metadata

def main():
    parser=argparse.ArgumentParser();parser.add_argument("--header",type=Path,default=ROOT/"external/dxvk-native/include/native/directx/d3d9.h")
    parser.add_argument("--output",type=Path,default=ROOT/"runtime");options=parser.parse_args()
    header=options.header.read_text(encoding="utf-8")
    calls,wrappers,metadata=generate(header);options.output.mkdir(parents=True,exist_ok=True)
    (options.output/"d3d9_methods.generated.inc").write_text(calls,encoding="utf-8")
    (options.output/"d3d9_wrappers.generated.inc").write_text(wrappers,encoding="utf-8")
    (options.output/"d3d9_abi.generated.json").write_text(json.dumps({"upstream_commit":"c8dc91fabd00cac11d697ccf07426e798393cd40","header_normalized_sha256":hashlib.sha256(header.encode()).hexdigest(),"methods":metadata},indent=2)+"\n",encoding="utf-8")
    print(f"Generated {len(metadata)} strict guest32 COM wrappers")
if __name__=="__main__":main()
